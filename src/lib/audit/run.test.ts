import { describe, expect, it } from "vitest";
import { fixtureSites, renderPage } from "../sample/fixtures";
import { evaluateCriteria } from "./rule";
import { CRITERION_EVALUATORS, RULES, runRules } from "./run";
import { DEFAULT_RULE_CONFIG, type Facts, type PageExpectations, type RuleConfig } from "./types";

const NW = fixtureSites("original")[0];
const page = (path: string, state: "original" | "fixed" = "original") => {
  const site = fixtureSites(state)[0];
  const p = site.pages.find((x) => x.path === path)!;
  return { html: renderPage(site, p), pageUrl: `${site.origin}${path}` };
};
const FULL_EXP: PageExpectations = { canonicalUrl: `${NW.origin}/tents/alpine-2p`, indexability: "index", important: true };

describe("runRules", () => {
  it("is deterministic for the same input", () => {
    expect(runRules(page("/tents/alpine-2p"), FULL_EXP)).toEqual(runRules(page("/tents/alpine-2p"), FULL_EXP));
  });

  it("finds the problems planted in the broken sample product page, and they are gone once fixed", () => {
    const codes = (state: "original" | "fixed") => runRules(page("/tents/alpine-2p", state), FULL_EXP).flatMap((r) => r.findings.map((f) => f.ruleCode));
    expect(codes("original")).toEqual(
      expect.arrayContaining(["title/multiple", "title/too-long", "canonical/expected-url", "structured-data/invalid-json", "images/missing-alt", "images/missing-dimensions"]),
    );
    expect(codes("fixed")).toEqual([]);
  });

  it("stores every required field on each finding", () => {
    const findings = runRules(page("/tents/alpine-2p"), FULL_EXP).flatMap((r) => r.findings);
    expect(findings.length).toBeGreaterThan(3);
    for (const f of findings) {
      expect(f.ruleCode).toMatch(/^[a-z-]+\/[a-z0-9-]+$/);
      expect(f.pageUrl).toBe(`${NW.origin}/tents/alpine-2p`);
      expect(f.observed).not.toBe("");
      expect(f.expected).not.toBe("");
      expect(f.why).not.toBe("");
      expect(["high", "medium", "low"]).toContain(f.severity);
      expect(["defect", "warning", "opportunity", "observation"]).toContain(f.kind);
      expect(["verified", "heuristic", "needs_review"]).toContain(f.certainty);
      expect(Object.keys(f.evidence.facts).length).toBeGreaterThan(0);
      expect(f.recommendations.length).toBeGreaterThan(0);
      expect(f.acceptanceCriteria.length).toBeGreaterThan(0);
      for (const c of f.acceptanceCriteria) expect(CRITERION_EVALUATORS[c.id], c.id).toBeDefined();
    }
  });

  it("runs only the response rule on non-HTML responses", () => {
    const results = runRules({ html: null, pageUrl: "https://example.com/x", response: { status: 404 } });
    expect(results.find((r) => r.ruleId === "http")?.findings.map((f) => f.ruleCode)).toEqual(["http/error-status"]);
    expect(results.filter((r) => r.ruleId !== "http").every((r) => r.status === "skipped")).toBe(true);
  });

  it("filters by category", () => {
    const results = runRules(page("/"), {}, { categories: ["metadata"] });
    expect(new Set(results.map((r) => r.category))).toEqual(new Set(["metadata"]));
  });
});

// Detection and verification must agree: if a check fires on some facts, those same facts must fail
// at least one of its acceptance criteria — otherwise a finding could "resolve" with the page unchanged.
// Each rule's fact cases are generated by observing real HTML variants, so they are realistic.
const VARIANTS: { head?: string; body?: string; status?: number; redirects?: number; headers?: Record<string, string>; lang?: string | null }[] = [
  {},
  { head: "<title>x</title>" },
  { head: "<title></title><title>Second</title>" },
  { head: `<title>${"Long title ".repeat(8)}</title><meta name="description" content="${"d".repeat(200)}">` },
  { head: '<meta name="description" content=""><meta name="description" content="short">' },
  { head: '<meta name="description" content="Too short.">' },
  { lang: null, head: '<link rel="alternate" hreflang="english" href="https://example.com/en">' },
  { lang: "en-UK" },
  { head: '<meta name="robots" content="noindex, nofollow"><link rel="canonical" href="https://other.example/">' },
  { head: '<meta name="robots" content="index, noindex"><link rel="canonical" href="https://example.com/p"><link rel="canonical" href="/q">' },
  { head: '<link rel="canonical" href="javascript:alert(1)">', headers: { "x-robots-tag": "noindex" } },
  { head: '<link rel="alternate" hreflang="en-UK" href="/uk">', body: "<h1></h1><h3>a</h3>" },
  { body: "<h1>A</h1><h1>B</h1><h2>c</h2><h4>d</h4>" },
  { head: '<script type="application/ld+json">{"@type":"Product",}</script>' },
  { head: '<script type="application/ld+json">{"@type":"Product","offers":{"@type":"Offer"}}</script>' },
  { body: '<img src="/a.jpg"><img src="/b.jpg" alt=""><img src="/c.jpg" alt="" role="presentation" width="1" height="1">' },
  { body: `<main><p>${"word ".repeat(400)}</p></main>`, head: '<meta property="og:title" content="t"><meta property="og:description" content="d"><meta property="og:image" content="/i.jpg">' },
  { status: 404 },
  { status: 503 },
  { redirects: 1 },
  { redirects: 3 },
];
const EXPS: PageExpectations[] = [
  {},
  { canonicalUrl: "https://example.com/p", indexability: "index", important: true },
  { indexability: "noindex", important: false },
  { indexability: "index", important: true },
];
const CONFIGS: RuleConfig[] = [DEFAULT_RULE_CONFIG, { thinContentWords: 1000, multipleH1: "warn" }];

function factSets(): { facts: Facts; ruleId: string }[] {
  const out: { facts: Facts; ruleId: string }[] = [];
  for (const v of VARIANTS) {
    const html = v.status && v.status >= 400 ? null : `<!doctype html><html${v.lang === null ? "" : ` lang="${v.lang ?? "en"}"`}><head>${v.head ?? ""}</head><body>${v.body ?? ""}</body></html>`;
    const chain = Array.from({ length: v.redirects ?? 0 }, (_, i) => ({ url: `https://example.com/r${i}`, status: 301 }));
    for (const r of runRules({ html, pageUrl: "https://example.com/p", headers: v.headers, response: { status: v.status ?? 200, redirectChain: chain, requestedUrl: chain[0]?.url ?? "https://example.com/p" } })) {
      if (r.status !== "skipped") out.push({ facts: r.facts, ruleId: r.ruleId });
    }
  }
  return out;
}

describe("detection/acceptance invariant", () => {
  const sets = factSets();
  for (const rule of RULES) {
    for (const check of rule.checks) {
      it(`${check.code}: detection implies a failing criterion`, () => {
        let fired = 0;
        for (const { facts, ruleId } of sets) {
          if (ruleId !== rule.id) continue;
          for (const exp of EXPS) {
            for (const config of CONFIGS) {
              if (!check.detect(facts, exp, config)) continue;
              fired++;
              const { results, unknown } = evaluateCriteria(check.criteria(exp, config), facts, CRITERION_EVALUATORS);
              expect(unknown).toEqual([]);
              expect(results.some((r) => !r.passed), JSON.stringify({ facts, exp })).toBe(true);
            }
          }
        }
        expect(fired, `no variant triggers ${check.code}; add one to VARIANTS`).toBeGreaterThan(0);
      });
    }
  }
});
